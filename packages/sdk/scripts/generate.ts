// Writes src/schema.ts from the API's OpenAPI document (phase-1-plan §6.3).
// The document comes from the app itself, with no server and no database,
// so CI can check that the committed types match the routes.
//
//   pnpm --filter @managemind/sdk generate
import { writeFileSync } from 'node:fs';
import { createApp } from '@managemind/api/app';
import openapiTS, { astToString } from 'openapi-typescript';

const env = {
  ENVIRONMENT: 'development',
  PLATFORM_NAME: 'managemind',
  PLATFORM_DOMAIN: 'localhost',
  STORE_DOMAIN: 'localhost',
};
const res = await createApp().request('/openapi.json', {}, env);
if (!res.ok) throw new Error(`/openapi.json answered ${res.status}`);
const document = await res.json();

const types = astToString(await openapiTS(document as Parameters<typeof openapiTS>[0]));
const header =
  "// Generated by scripts/generate.ts from the API's OpenAPI document. Do not edit.\n// Run `pnpm --filter @managemind/sdk generate` after changing a route.\n\n";
writeFileSync(new URL('../src/schema.ts', import.meta.url), header + types);
console.log('Wrote src/schema.ts');
